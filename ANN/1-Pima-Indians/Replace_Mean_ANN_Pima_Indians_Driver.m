%% Import Predictors/Targets
data = readmatrix("pima-indians-diabetes.csv", 'NumHeaderLines', 1); % read from csv
predictors = data(:,1:end-1);
target = data(:,end);
VarName = {'Preg'; 'Glucose'; 'Blood Pressure'; 
    'Skin Thickness'; 'Insulin';
    'BMI'; 'DPF'; 'Age'};

%% Pre-Processing
% TODO: pre-process the dataset
% Need to replace missing data (0s) to improve net performance
% Any other things?

%% Pre-Processing
% Identify columns with missing values
columns_to_check = [2, 3, 4, 5, 6]; % Glucose, BP, Skin, Insulin, BMI
column_names = {'Glucose', 'Blood Pressure', 'Skin Thickness', 'Insulin', 'BMI'};

% Create a copy of predictors for preprocessing
predictors_clean = predictors;

% For each column, replace 0s with the mean of non-zero values
for i = 1:length(columns_to_check)
    col = columns_to_check(i);
    non_zero_values = predictors(:, col);
    non_zero_values = non_zero_values(non_zero_values > 0);
    
    % Calculate mean of non-zero values
    col_mean = mean(non_zero_values);
    
    % Replace zeros with mean
    zero_indices = predictors(:, col) == 0;
    predictors_clean(zero_indices, col) = col_mean;
    
    % Display statistics about replacements
    num_replaced = sum(zero_indices);
    fprintf('Column %s: Replaced %d missing values with mean = %.2f\n', ...
            column_names{i}, num_replaced, col_mean);
end

%% Solve an Input-Output Fitting problem with a Neural Network
% Script generated by Neural Fitting app
% Created 24-Mar-2025 00:14:08
%
% This script assumes these variables are defined:
%
%   predictors - input data.
%   target - target data.

x = predictors_clean';
t = target';

%% Choose a Training Function
% TODO: replace with optimizer which works with cross-entropy
% such as Adam optimizer
% For now, using Levenberg–Marquardt (trainlm)
trainFcn = 'trainlm';

%% Hidden layer size
% Arbitrary hidden layer size
hiddenLayerSize = 20;
net = patternnet(hiddenLayerSize, trainFcn);

%% Activation functions
% ReLU activation from input -> hidden layer
% can be changed
net.layers{1}.transferFcn = 'poslin';   
% Sigmoid activation from hidden -> output layer
% This allows for output to be a probability between 0 and 1
net.layers{2}.transferFcn = 'logsig';    

%% Loss criterion (defaults to MSE)
% Set performance function to cross-entropy for binary targets
% outcome vector (target):
    % 0 = doesn't have diabetes
    % 1 = has diabetes
% net.performFcn = 'crossentropy';

%% Training/Validation/Testing Split
% Default division for now*
net.divideParam.trainRatio = 70/100;
net.divideParam.valRatio = 15/100;
net.divideParam.testRatio = 15/100;

%% Perform Train/Validate/Test
% Train the Network
[net,tr] = train(net,x,t);

% Test the Network
y = net(x);
e = gsubtract(t,y);
performance = perform(net,t,y);

% View the Network
% view(net);

%% Calculate classification accuracy
N = length(t);
numCorrect=0;
yDisc = round(y);
for i=1:N
    % Can change this threshold
    % For now, round outputs to 0 or 1
    if yDisc(i) == t(i)
        numCorrect = numCorrect+1;
    end
end
accuracy = numCorrect/N*100;
fprintf('Classification accuracy: %.2f\n', accuracy);

%% Visualization: Confusion Matrix
confMat = confusionmat(t, yDisc);
figure;
confusionchart(confMat, {'No Diabetes', 'Diabetes'});
title('Confusion Matrix');

