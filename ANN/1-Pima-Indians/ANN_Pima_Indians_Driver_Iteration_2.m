% Sections modified from MATLAB's ANN -> generated script
clear variables;
clc;
close all;

%% Import Predictors/Targets
data = readmatrix("pima-indians-diabetes.csv", 'NumHeaderLines', 1); % read from csv
predictors = data(:,1:end-1);
target = data(:,end);
VarName = {'Preg'; 'Glucose'; 'Blood Pressure'; 
    'Skin Thickness'; 'Insulin';
    'BMI'; 'DPF'; 'Age'};

%% Pre-Processing
% Identify columns with missing values
columns_to_check = [2, 3, 4, 5, 6]; % Glucose, BP, Skin, Insulin, BMI
column_names = {'Glucose', 'Blood Pressure', 'Skin Thickness', 'Insulin', 'BMI'};

% Identify rows with missing values
has_missing = false(size(predictors, 1), 1);
% for i = 1:length(columns_to_check)
%     col = columns_to_check(i);
%     zero_indices = predictors(:, col) == 0;
%     has_missing = has_missing | zero_indices;
%     fprintf('Column %s has %d missing values (zeros)\n', column_names{i}, sum(zero_indices));
% end

% Remove rows with missing values
complete_cases = ~has_missing;
fprintf('Removing %d rows with missing data (%.1f%% of the dataset)\n', ...
        sum(has_missing), 100*sum(has_missing)/length(has_missing));
fprintf('Keeping %d complete cases (%.1f%% of the dataset)\n', ...
        sum(complete_cases), 100*sum(complete_cases)/length(complete_cases));

% Create clean dataset with complete cases
predictors_clean = predictors(complete_cases, :);
target_clean = target(complete_cases);

%% Solve an Input-Output Fitting problem with a Neural Network
% Script generated by Neural Fitting app
% Created 24-Mar-2025 00:14:08
%
% This script assumes these variables are defined:
%
%   predictors - input data.
%   target - target data.

[xn, ps] = mapminmax(predictors_clean'); % try normalize the inputs
x = xn;
%x = predictors_clean';
t = target_clean';                       % targets are already binary

%% Seed for Reproducibility
rng(999);

%% Cross-validation Setup
K = 5;
cv = cvpartition(size(x, 2), 'KFold', K);

% Init arrays for metrics
accuracies = zeros(K, 1);
precisions = zeros(K, 1);
recalls = zeros(K, 1);

% confusion matrix over all folds
combinedConfMat = zeros(2, 2);

for k = 1:K
    fprintf('Fold %d\n', k);

    % Get training and test indices
    trainIdx = training(cv, k);
    testIdx = test(cv, k);

    xTrain = x(:, trainIdx);
    tTrain = t(:, trainIdx);
    xTest = x(:, testIdx);
    tTest = t(:, testIdx);

    %% Define Net
    trainFcn = 'trainscg';
    hiddenLayers = [15 15 15];
    net = patternnet(hiddenLayers, trainFcn);

    % Internal validation set to prevent overfitting
    net.divideParam.trainRatio = 90/100;
    net.divideParam.valRatio = 10/100;
    net.divideParam.testRatio = 0;
    net.trainParam.max_fail = 10;

    % Activation functions
    net.layers{1}.transferFcn = 'poslin';
    net.layers{2}.transferFcn = 'poslin';
    net.layers{3}.transferFcn = 'poslin';
    net.layers{4}.transferFcn = 'logsig';

    % Loss function
    net.performFcn = 'crossentropy';

    % Train
    [net, ~] = train(net, xTrain, tTrain);

    % Test
    yTest = net(xTest);
    % Threshold changed to 0.4 to favour recall
    thresh = 0.4;
    yDisc = double(yTest >= thresh);

    % Compute confusion matrix
    confMat = confusionmat(tTest, yDisc);

    % Store total
    combinedConfMat = combinedConfMat + confMat;

    TN = confMat(1,1);
    FN = confMat(2,1);
    FP = confMat(1,2);
    TP = confMat(2,2);
    % Metrics
    % correct predictions out of all predictions
    accuracy = (TP + TN) / (TN + FN + FP + TP) * 100;
    % correct diabetes prediction out of all diabetes predictions
    precision = TP / (TP + FP) * 100;
    % correct diabetes prediction out of all those who actually have diabetes
    recall = TP / (TP + FN) * 100;

    % Store
    accuracies(k) = accuracy;
    precisions(k) = precision;
    recalls(k) = recall;

    fprintf('Accuracy: %.2f%%\n', accuracy);
    fprintf('Precision: %.2f%%\n', precision);
    fprintf('Recall: %.2f%%\n', recall);
end

%% Final Report
fprintf('\nFinal Results (Avg over %d folds) \n', K);
fprintf('Average Accuracy: %.2f%%\n', mean(accuracies));
fprintf('Average Precision: %.2f%%\n', mean(precisions));
fprintf('Average Recall: %.2f%%\n', mean(recalls));

%% Combined confusion matrix
figure;
confusionchart(combinedConfMat, {'No Diabetes', 'Diabetes'});
title('Combined Confusion Matrix (Across All Folds)');
