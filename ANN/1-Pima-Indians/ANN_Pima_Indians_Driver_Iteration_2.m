% Sections modified from MATLAB's ANN -> generated script
clear variables;
clc;
close all;

%% Import Predictors/Targets
data = readmatrix("pima-indians-diabetes.csv", 'NumHeaderLines', 1); % read from csv
predictors = data(:,1:end-1);
target = data(:,end);
VarName = {'Preg'; 'Glucose'; 'Blood Pressure'; 
    'Skin Thickness'; 'Insulin';
    'BMI'; 'DPF'; 'Age'};

%% Pre-Processing
% Identify columns with missing values
columns_to_check = [2, 3, 4, 5, 6]; % Glucose, BP, Skin, Insulin, BMI
column_names = {'Glucose', 'Blood Pressure', 'Skin Thickness', 'Insulin', 'BMI'};

% Identify rows with missing values
has_missing = false(size(predictors, 1), 1);
for i = 1:length(columns_to_check)
    col = columns_to_check(i);
    zero_indices = predictors(:, col) == 0;
    has_missing = has_missing | zero_indices;
    fprintf('Column %s has %d missing values (zeros)\n', column_names{i}, sum(zero_indices));
end

% Remove rows with missing values
complete_cases = ~has_missing;
fprintf('Removing %d rows with missing data (%.1f%% of the dataset)\n', ...
        sum(has_missing), 100*sum(has_missing)/length(has_missing));
fprintf('Keeping %d complete cases (%.1f%% of the dataset)\n', ...
        sum(complete_cases), 100*sum(complete_cases)/length(complete_cases));

% Create clean dataset with complete cases
predictors_clean = predictors(complete_cases, :);
target_clean = target(complete_cases);

%% Solve an Input-Output Fitting problem with a Neural Network
% Script generated by Neural Fitting app
% Created 24-Mar-2025 00:14:08
%
% This script assumes these variables are defined:
%
%   predictors - input data.
%   target - target data.

[xn, ps] = mapminmax(predictors_clean'); % try normalize the inputs
x = xn;
%x = predictors_clean';
t = target_clean';                       % targets are already binary

%% Choose a Training Function
trainFcn = 'trainscg'; % for cross entropy

%% Hidden layer size
hiddenLayerSize = [15 15 10];
net = patternnet(hiddenLayerSize, trainFcn);
net.trainParam.epochs = 1000;
net.trainParam.max_fail = 50;

%% Activation functions
% ReLU activation from input -> HL1, and HL1 -> HL2
net.layers{1}.transferFcn = 'poslin';   
net.layers{2}.transferFcn = 'poslin';  
net.layers{3}.transferFcn = 'poslin';  

% Sigmoid activation from final HL -> output
% This allows for output to be a probability between 0 and 1
net.layers{4}.transferFcn = 'logsig';    

%% Loss criterion (defaults to MSE)
net.performFcn = 'crossentropy';

%% Training/Validation/Testing Split
% Default division for now*
net.divideParam.trainRatio = 70/100;
net.divideParam.valRatio = 15/100;
net.divideParam.testRatio = 15/100;

%% Perform Train/Validate/Test
% Train the Network
[net,tr] = train(net,x,t);

% Test the Network
y = net(x);
e = gsubtract(t,y);
performance = perform(net,t,y);

% View the Network
view(net);

%% Calculate classification accuracy
N = length(t);
numCorrect=0;
thresh = 0.5;
yDisc = double(y >= thresh);
for i=1:N
    if yDisc(i) == t(i)
        numCorrect = numCorrect+1;
    end
end
accuracy = numCorrect/N*100;
fprintf('Classification accuracy: %.2f\n%', accuracy);

%% Visualization: Confusion Matrix
confMat = confusionmat(t, yDisc);
figure;
confusionchart(confMat, {'No Diabetes', 'Diabetes'});
title('Confusion Matrix');

%% Plots
% Uncomment these lines to enable various plots.
figure, plotperform(tr)
%figure, plottrainstate(tr)
%figure, ploterrhist(e)

fprintf('Cross-Entropy Loss: %.6f\n', performance);


